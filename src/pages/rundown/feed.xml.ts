import rss from '@astrojs/rss';
import type { APIContext } from 'astro';
import { getIssues } from '../../lib/data';
import { plain } from '../../lib/md';

export async function GET(context: APIContext) {
  const issues = await getIssues();
  return rss({
    title: 'Inference Rundown & Weekly Digest',
    description: 'A weekly briefing on LLM inference, generated by Claude from public sources.',
    site: context.site!,
    items: issues.map((i) => ({
      title: `#${i.data.issue}: ${i.data.headline}`,
      pubDate: new Date(`${i.id}T12:00:00Z`),
      description: plain(i.data.tldr),
      link: `/rundown/${i.id}/`,
    })),
  });
}
